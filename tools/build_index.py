"""Rebuild INDEX.md from the front matter of every analysis and idea README.

    pixi run index

INDEX.md is generated: edit the READMEs, not the index.
"""

from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ANALYSES = ROOT / "analyses"
STATUS_ORDER = {"active": 0, "idea": 1, "done": 2, "dropped": 3}


def front_matter(readme: Path) -> dict:
    text = readme.read_text()
    if not text.startswith("---"):
        return {}
    try:
        meta = yaml.safe_load(text.split("---", 2)[1]) or {}
    except yaml.YAMLError as e:
        print(f"warning: bad front matter in {readme.relative_to(ROOT)}: {e}")
        return {}
    meta["tags"] = meta.get("tags") or []
    return meta


def row(meta: dict, link: str, indent: str = "") -> str:
    tags = " ".join(f"`{t}`" for t in meta["tags"])
    q = meta.get("question") or ""
    return (f"{indent}- [{meta.get('title') or link}]({link}) · **{meta.get('status', '?')}** · "
            f"{meta.get('created', '')} {tags}" + (f"\n{indent}  {q}" if q else ""))


def main() -> None:
    by_topic: dict[str, list[str]] = defaultdict(list)
    by_tag: dict[str, list[str]] = defaultdict(list)
    counts: dict[str, int] = defaultdict(int)

    for folder in sorted(p for p in ANALYSES.iterdir() if p.is_dir()) if ANALYSES.exists() else []:
        readme = folder / "README.md"
        if not readme.exists():
            continue
        meta = front_matter(readme)
        link = f"analyses/{folder.name}/"
        topic = folder.name.split("-", 1)[0]
        lines = [row(meta, link)]
        counts[meta.get("status", "?")] += 1
        for t in meta["tags"]:
            by_tag[t].append(f"[{folder.name}]({link})")

        ideas = []
        for idea in sorted(p for p in (folder / "ideas").glob("*/") if p.is_dir()):
            if not (idea / "README.md").exists():
                continue
            im = front_matter(idea / "README.md")
            ilink = f"{link}ideas/{idea.name}/"
            parent = im.get("parent") or folder.name
            ideas.append((STATUS_ORDER.get(im.get("status"), 9), idea.name, im, ilink, parent))
            counts[im.get("status", "?")] += 1
            for t in im["tags"]:
                by_tag[t].append(f"[{folder.name}/{idea.name}]({ilink})")
        for _, name, im, ilink, parent in sorted(ideas):
            branch = f" ← {parent}" if parent != folder.name else ""
            lines.append(row(im, ilink, "  ") + branch)
        by_topic[topic].append("\n".join(lines))

    out = ["# Index", "", "Generated by `pixi run index` from README front matter. Do not edit.", ""]
    out.append("Status: " + (", ".join(f"{k} {v}" for k, v in sorted(counts.items())) or "empty"))
    out.append("")
    for topic in sorted(by_topic):
        out += [f"## {topic}", "", *by_topic[topic], ""]
    if by_tag:
        out += ["## By tag", ""]
        for t in sorted(by_tag):
            out.append(f"- `{t}`: " + ", ".join(by_tag[t]))
        out.append("")
    (ROOT / "INDEX.md").write_text("\n".join(out))
    print("INDEX.md rebuilt")


if __name__ == "__main__":
    main()
